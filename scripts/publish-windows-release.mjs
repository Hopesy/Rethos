import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFileSync, spawnSync } from "node:child_process";
import { appendFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const repository = process.env.GITHUB_REPOSITORY;
assert.equal(repository, "Hopesy/Rethos");
const directory = "release/windows-assets";
const info = JSON.parse(readFileSync(join(directory, "BUILD-INFO.json"), "utf8"));
assert.equal(info.version, process.env.RELEASE_VERSION);
assert.match(info.version, /^\d+\.\d+\.\d+$/);
assert.equal(info.commit, process.env.RELEASE_SHA);
assert.match(info.commit, /^[a-f0-9]{40}$/);
assert.equal(info.signed, false);
const expected = [`Rethos-${info.version}-setup.exe`, `Rethos-${info.version}-setup.exe.blockmap`, `Rethos-${info.version}-x64.zip`, "Rethos-setup.exe", "latest.yml", "SHA256SUMS-windows-x64.txt"];
assert.deepEqual(Object.keys(info.files).sort(), [...expected].sort());
assert.deepEqual(readdirSync(directory).sort(), [...expected, "BUILD-INFO.json"].sort());
const hash = name => createHash("sha256").update(readFileSync(join(directory, name))).digest("hex");
for (const name of expected) assert.equal(hash(name), info.files[name], `artifact changed: ${name}`);
assert.equal(hash("Rethos-setup.exe"), hash(`Rethos-${info.version}-setup.exe`));
const hashes = new Map([...expected, "BUILD-INFO.json"].map(name => [name, `sha256:${hash(name)}`]));
const tag = `v${info.version}`;
const gh = args => execFileSync("gh", args, { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] }).trim();
const view = () => JSON.parse(gh(["release", "view", tag, "--repo", repository, "--json", "isDraft,targetCommitish,assets,url"]));
const probe = spawnSync("gh", ["release", "view", tag, "--repo", repository], { encoding: "utf8" });
if (probe.status === 0) {
  const existing = view();
  assert(existing.isDraft, "this version is already published; bump package.json first");
  assert.equal(existing.targetCommitish, info.commit, "draft belongs to another source commit");
  assert(existing.assets.every(asset => hashes.has(asset.name)), "draft contains another platform's assets");
} else {
  assert(/release not found|HTTP 404/i.test(probe.stderr), `release lookup failed: ${probe.stderr}`);
  mkdirSync(".Rethos-temp/desktop-release", { recursive: true });
  const notes = `.Rethos-temp/desktop-release/notes.md`;
  writeFileSync(notes, `Rethos ${info.version} · Windows x64\n\n- 安装程序：\`Rethos-${info.version}-setup.exe\`（固定下载名：\`Rethos-setup.exe\`）。\n- 便携包：\`Rethos-${info.version}-x64.zip\`，解压后运行 \`Rethos.exe\`。\n- 工作流验证：浏览器、独立服务端、NSIS 安装、桌面渲染和更新文件哈希。\n- 当前 Windows 包未签名，首次打开可能出现 Windows SmartScreen 提示。\n- 来源提交：\`${info.commit}\`，校验文件：\`SHA256SUMS-windows-x64.txt\`。\n\n使用与更新：[发布文档](https://github.com/${repository}/blob/${info.commit}/docs/releasing.md)。VPS 与手机网页继续使用现有部署入口。\n`);
  gh(["release", "create", tag, "--repo", repository, "--target", info.commit, "--draft", "--title", `Rethos ${info.version} · Windows`, "--notes-file", notes]);
}
gh(["release", "upload", tag, ...[...hashes.keys()].map(name => join(directory, name)), "--repo", repository, "--clobber"]);
const staged = view();
assert.equal(staged.assets.length, hashes.size);
for (const asset of staged.assets) assert.equal(asset.digest, hashes.get(asset.name), `uploaded bytes differ: ${asset.name}`);
const tagProbe = spawnSync("gh", ["api", `repos/${repository}/commits/${tag}`, "--jq", ".sha"], { encoding: "utf8" });
if (tagProbe.status === 0) assert.equal(tagProbe.stdout.trim(), info.commit, "release tag points to another commit");
else assert(/HTTP 404|No commit found/i.test(tagProbe.stderr), `tag lookup failed: ${tagProbe.stderr}`);
gh(["release", "edit", tag, "--repo", repository, "--draft=false", "--latest"]);
const published = view();
assert.equal(published.isDraft, false);
assert.equal(gh(["api", `repos/${repository}/commits/${tag}`, "--jq", ".sha"]), info.commit);
console.log(published.url);
if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, `## Rethos Windows release\n\n${published.url}\n\nSource: \`${info.commit}\` · unsigned Windows x64 · ${hashes.size} verified assets\n`);
